#!/usr/bin/env python3
"""
Stage 1: Macro Generator
========================
Reads config.yaml and generates one ImageJ macro per time point.
Each macro handles all three channels (red, green, blue) in sequence.

Calibration mean gray values are read from pre-generated .txt files
in the calibrations directory (produced automatically by the pipeline
after processing the calibration photo for each time point).

Usage:
    python scripts/generate_macros.py
    python scripts/generate_macros.py --timepoint 10.02.2026
    python scripts/generate_macros.py --dry-run
"""

import argparse
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    print("ERROR: PyYAML not installed. Run: pip install pyyaml")
    sys.exit(1)


# ── Helpers ────────────────────────────────────────────────────────────────────

def load_config(config_path: Path) -> dict:
    with open(config_path) as f:
        return yaml.safe_load(f)


def to_ij_path(path) -> str:
    """Forward slashes required by ImageJ even on macOS."""
    return Path(path).as_posix()


def fmt_values(values: list) -> str:
    return " ".join(str(v) for v in values)


def find_calibration_txt(calibrations_dir: Path, date_short: str, channel: str) -> Path | None:
    """Find the calibration .txt file for a given date and channel."""
    expected = calibrations_dir / f"{date_short}_calibration_{channel}.txt"
    return expected if expected.exists() else None


# ── Macro builder ──────────────────────────────────────────────────────────────

def build_macro(tp: dict, config: dict, cal_values: dict) -> str:
    """
    Build a complete ImageJ macro for one time point.

    cal_values: dict with keys 'red', 'green', 'blue', each containing
                a dict with 'file' and 'mean_values' keys.
    """
    paths        = config["paths"]
    standards    = config["reflectance_standards"]
    cal_fn       = config["calibration_function"]
    roi_map_file = config["roi_map"]
    date_short   = tp["date_short"]

    cal_dir      = to_ij_path(paths["calibrations_dir"])
    roi_map_path = to_ij_path(str(Path(paths["roi_maps_dir"]) / roi_map_file))
    results_dir  = to_ij_path(paths["results_dir"])
    std_str      = fmt_values(standards)

    red   = cal_values["red"]
    green = cal_values["green"]
    blue  = cal_values["blue"]

    macro = f'''\
// ============================================================
// Kelp Reflectance Macro — {tp["label"]}
// Auto-generated by generate_macros.py — DO NOT EDIT MANUALLY
// Regenerate by running: python scripts/generate_macros.py
// ============================================================

// -- Rotation helpers ----------------------------------------
macro "rotate pos [p]" {{
    run("Rotate... ", "angle=0.50 grid=1 interpolation=Bilinear");
}}

macro "rotate neg [n]" {{
    run("Rotate... ", "angle=-0.50 grid=1 interpolation=Bilinear");
}}

// -- ROI map loader ------------------------------------------
macro "load ROIs [l]" {{
    roiManager("Open", "{roi_map_path}");
    roiManager("Show All");
    roiManager("Show All with labels");
}}

// -- ROI shift helpers (20px per keypress) -------------------
macro "all roi down [s]" {{
    requires("1.38e");
    dx = 0; dy = 20;
    n = roiManager("count");
    if (n == 0) exit("ROI Manager is empty");
    for (i = 0; i < n; i++) {{
        roiManager("select", i);
        getSelectionBounds(x, y, w, h);
        setSelectionLocation(x + dx, y + dy);
    }}
    roiManager("Update");
}}

macro "all roi up [w]" {{
    requires("1.38e");
    dx = 0; dy = -20;
    n = roiManager("count");
    if (n == 0) exit("ROI Manager is empty");
    for (i = 0; i < n; i++) {{
        roiManager("select", i);
        getSelectionBounds(x, y, w, h);
        setSelectionLocation(x + dx, y + dy);
    }}
    roiManager("Update");
}}

macro "all roi left [a]" {{
    requires("1.38e");
    dx = -20; dy = 0;
    n = roiManager("count");
    if (n == 0) exit("ROI Manager is empty");
    for (i = 0; i < n; i++) {{
        roiManager("select", i);
        getSelectionBounds(x, y, w, h);
        setSelectionLocation(x + dx, y + dy);
    }}
    roiManager("Update");
}}

macro "all roi right [d]" {{
    requires("1.38e");
    dx = 20; dy = 0;
    n = roiManager("count");
    if (n == 0) exit("ROI Manager is empty");
    for (i = 0; i < n; i++) {{
        roiManager("select", i);
        getSelectionBounds(x, y, w, h);
        setSelectionLocation(x + dx, y + dy);
    }}
    roiManager("Update");
}}

// -- Measure all three channels ------------------------------
macro "measure [m]" {{
    imgTitle = getTitle();
    baseName = imgTitle;
    suffixes = newArray(".jpg", ".jpeg", ".tif", ".tiff", ".png");
    for (i = 0; i < suffixes.length; i++) {{
        baseName = replace(baseName, suffixes[i], "");
    }}

    run("RGB Stack");

    // Red channel
    setSlice(1);
    run("Calibrate...", "open=[{cal_dir}/{red["file"]}] function=[{cal_fn}] unit=[Gray Value] text1=[ {fmt_values(red["mean_values"])} ] text2=[{std_str}] show");
    close();
    roiManager("Measure");
    saveAs("Results", "{results_dir}/" + baseName + "_red.csv");
    run("Clear Results");

    // Green channel
    setSlice(2);
    run("Calibrate...", "open=[{cal_dir}/{green["file"]}] function=[{cal_fn}] unit=[Gray Value] text1=[ {fmt_values(green["mean_values"])} ] text2=[{std_str}] show");
    close();
    roiManager("Measure");
    saveAs("Results", "{results_dir}/" + baseName + "_green.csv");
    run("Clear Results");

    // Blue channel
    setSlice(3);
    run("Calibrate...", "open=[{cal_dir}/{blue["file"]}] function=[{cal_fn}] unit=[Gray Value] text1=[ {fmt_values(blue["mean_values"])} ] text2=[{std_str}] show");
    close();
    roiManager("Measure");
    saveAs("Results", "{results_dir}/" + baseName + "_blue.csv");
    run("Clear Results");

    print("Done: " + baseName);
}}
'''
    return macro


# ── Main ───────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(
        description="Generate ImageJ macros from config.yaml"
    )
    parser.add_argument("--config", default="config.yaml")
    parser.add_argument("--timepoint", default=None,
                        help="Only generate for this time point label (e.g. 10.02.2026)")
    parser.add_argument("--dry-run", action="store_true",
                        help="Print macros without writing files")
    args = parser.parse_args()

    config_path = Path(args.config)
    if not config_path.exists():
        print(f"ERROR: Config not found: {config_path}")
        sys.exit(1)

    config         = load_config(config_path)
    macros_dir     = Path(config["paths"]["macros_dir"])
    cal_dir        = Path(config["paths"]["calibrations_dir"])

    if not args.dry_run:
        macros_dir.mkdir(parents=True, exist_ok=True)

    time_points = config.get("time_points", [])
    if args.timepoint:
        time_points = [tp for tp in time_points if tp["label"] == args.timepoint]
        if not time_points:
            print(f"ERROR: Time point '{args.timepoint}' not found in config.")
            sys.exit(1)

    print(f"Generating macros for {len(time_points)} time point(s)...\n")

    generated, skipped = [], []

    for tp in time_points:
        label      = tp["label"]
        date_short = tp["date_short"]

        # Find calibration files for all three channels
        cal_values = {}
        missing    = []

        for channel in ["red", "green", "blue"]:
            cal_file = find_calibration_txt(cal_dir, date_short, channel)
            if cal_file is None:
                missing.append(f"{date_short}_calibration_{channel}.txt")
            else:
                # Read mean values from the calibration txt file
                # Expected format: one float per line
                try:
                    lines = cal_file.read_text().strip().splitlines()
                    mean_values = [float(l.split()[0]) for l in lines if l.strip()]
                    cal_values[channel] = {
                        "file": cal_file.name,
                        "mean_values": mean_values,
                    }
                except Exception as e:
                    missing.append(f"{cal_file.name} (parse error: {e})")

        if missing and not args.dry_run:
            print(f"  [SKIP] {label} — missing or unreadable calibration files:")
            for f in missing:
                print(f"         {f}")
            print(f"         Run the calibration step first for this time point.")
            skipped.append(label)
            continue

        # Use placeholder values for dry run
        if args.dry_run and missing:
            for channel in ["red", "green", "blue"]:
                if channel not in cal_values:
                    cal_values[channel] = {
                        "file": f"{date_short}_calibration_{channel}.txt",
                        "mean_values": [200.0, 162.0, 136.0, 92.0, 50.0, 11.0],
                    }

        macro_content = build_macro(tp, config, cal_values)
        output_path   = macros_dir / f"{date_short}_macro.ijm"

        if args.dry_run:
            print(f"{'='*60}")
            print(f"  DRY RUN — would write: {output_path}")
            print(f"{'='*60}")
            print(macro_content)
        else:
            output_path.write_text(macro_content)
            print(f"  [OK]  {output_path.name}")
            generated.append(str(output_path))

    print()
    if args.dry_run:
        print(f"Dry run complete. {len(time_points)} macro(s) previewed.")
    else:
        print(f"Done. {len(generated)} macro(s) generated", end="")
        if skipped:
            print(f", {len(skipped)} skipped ({', '.join(skipped)}).")
        else:
            print(".")
        if generated:
            print(f"\nMacros saved to: {macros_dir}")
            print("\nNext: open Fiji → Plugins > Macros > Install → select the .ijm file")


if __name__ == "__main__":
    main()
